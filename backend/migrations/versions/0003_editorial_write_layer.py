TRIGGERS = """
CREATE FUNCTION public.azir_touch_updated_at()
RETURNS trigger
LANGUAGE plpgsql
AS $fn$
BEGIN
    NEW.updated_at := now();
    RETURN NEW;
END;
$fn$;
""" + "".join(
    f"""
CREATE TRIGGER trg_{table}_updated
    BEFORE UPDATE ON public.{table}
    FOR EACH ROW EXECUTE FUNCTION public.azir_touch_updated_at();"""
    for table in (*ENTITY_TABLES, "editorial_state")
)


