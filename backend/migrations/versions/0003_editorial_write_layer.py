"""Editorial write layer: identities, sessions, workflow metadata, lint runs (ADR-0010).

The public read model does not change: entities keep ``status`` and ``revision`` as the single
source of truth for *where* a record is in the review loop. What this migration adds is the
machinery that makes a write trustworthy:

* ``app_user.password_hash`` + ``app_session`` -- argon2id credentials and opaque session tokens
  (the table stores only the SHA-256 digest of the cookie value, never the cookie itself).
* ``editorial_state`` -- who submitted / reviewed / published / archived, when, and with what
  note, plus ``head_id``, the link that implements the reviewed-copy pattern: editing a published
  entity creates a draft row whose ``head_id`` points at the live record, so the public version is
  never half-edited.
* ``lint_run`` -- every data-lint report, so "we checked" is a fact with a timestamp (docs/07 §3).
* CHECK constraints on the vocabularies, because a typo in a status must fail at the database, not
  silently disappear from a filter.

Revision ID: 0003_editorial_write_layer
Revises: 0002_search_normalisation
Create Date: 2026-09-13
"""

from __future__ import annotations

